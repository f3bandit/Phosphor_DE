# Phosphor_DE splash: amber phosphor wordmark with bloom, scanlines and an aperture-grille mask.
# Rendered with DejaVu Sans Mono Bold (free licence). Output: GBA BGR555 240x160 + PNG preview.
import sys
from PIL import Image, ImageDraw, ImageFont, ImageFilter
W,H=240,160
AMB=(240,168,48)
F=ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf',30)
FS=ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf',11)
FT=ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf',9)
def text_layer(txt,font,fill,xy=None,anchor='mm'):
    L=Image.new('RGB',(W,H),(0,0,0)); d=ImageDraw.Draw(L)
    d.text(xy or (W//2,H//2),txt,font=font,fill=fill,anchor=anchor); return L
base=Image.new('RGB',(W,H),(10,9,12))
# soft radial vignette glow behind the logo
glow=Image.new('L',(W,H),0); gd=ImageDraw.Draw(glow); gd.ellipse([20,30,220,110],fill=90); glow=glow.filter(ImageFilter.GaussianBlur(28))
base=Image.composite(Image.new('RGB',(W,H),(46,30,10)),base,glow)
word=text_layer('PHOSPHOR',F,AMB,(W//2,68))
bloom=word.filter(ImageFilter.GaussianBlur(6))
bloom2=word.filter(ImageFilter.GaussianBlur(2))
def add(a,b,k=1.0):
    return Image.eval(Image.blend(a,b,0.5),lambda v:v).point(lambda v:v) if False else Image.fromarray(None) if False else _add(a,b,k)
def _add(a,b,k):
    pa=a.load(); pb=b.load(); o=Image.new('RGB',(W,H)); po=o.load()
    for y in range(H):
        for x in range(W):
            po[x,y]=tuple(min(255,int(pa[x,y][i]+pb[x,y][i]*k)) for i in range(3))
    return o
img=_add(base,bloom,0.9); img=_add(img,bloom2,0.6); img=_add(img,word,1.0)
d=ImageDraw.Draw(img)
# "DE" pill under the wordmark
d.rounded_rectangle([104,88,136,102],radius=3,outline=AMB,fill=(30,22,8))
d.text((120,95),'DE',font=FS,fill=AMB,anchor='mm')
# scanlines + aperture grille (phosphor stripes)
px=img.load()
for y in range(H):
    for x in range(W):
        r,g,b=px[x,y]
        if y%2: r,g,b=int(r*0.72),int(g*0.72),int(b*0.72)
        m=x%3; k=(1.08,0.94,0.94) if m==0 else (0.94,1.08,0.94) if m==1 else (0.94,0.94,1.08)
        px[x,y]=(min(255,int(r*k[0])),min(255,int(g*k[1])),min(255,int(b*k[2])))
# small print in the UI's own pixel font (Tamzen Bold 6x12), drawn after the CRT effect so it stays sharp
import os, re
_hdr = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'source', 'norcheck', 'font_tamzenb.h')).read()
FONT = [int(v, 16) for v in re.findall(r'0x([0-9A-F]{2})', _hdr.split('{', 1)[1])]
def pixtext(y, txt, col, shadow=(0, 0, 0)):
    x0 = (W - len(txt) * 6) // 2
    for dx, dy, c in ((1, 1, shadow), (0, 0, col)):
        for i, ch in enumerate(txt):
            g = FONT[ord(ch) * 12:(ord(ch) + 1) * 12]
            for r in range(12):
                for b in range(6):
                    if g[r] & (0x80 >> b):
                        X, Y = x0 + i * 6 + b + dx, y + r + dy
                        if 0 <= X < W and 0 <= Y < H: px[X, Y] = c
pixtext(110, 'EZ-FLASH OMEGA DEFINITIVE EDITION', (214, 210, 202))
pixtext(140, 'by f3bandit', (240, 168, 48))
img.save(sys.argv[1]+'.png')
img.resize((W*3,H*3),Image.NEAREST).save(sys.argv[1]+'_3x.png')
# GBA BGR555, little endian bytes, grit-style header
data=bytearray()
for y in range(H):
    for x in range(W):
        r,g,b=px[x,y]; v=(r>>3)|((g>>3)<<5)|((b>>3)<<10); data+=bytes((v&0xFF,v>>8))
with open(sys.argv[1]+'.h','w') as f:
    f.write('// Phosphor_DE splash, 240x160@16, generated by art/make_splash.py\n')
    f.write('const unsigned char gImage_SPLASH[76800] __attribute__((aligned(4)))=\n{\n')
    for i in range(0,len(data),16): f.write('\t'+','.join('0x%02X'%v for v in data[i:i+16])+',\n')
    f.write('};\n')
